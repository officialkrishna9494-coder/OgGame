export type CanvasIcon = keyof typeof PATHS;

const cache = new Map<CanvasIcon, Path2D>();

/** Paint an icon centred on (cx, cy), `size` px square. */
export function drawIcon(g: CanvasRenderingContext2D, name: CanvasIcon, cx: number, cy: number, size: number, color: string) {
  let path = cache.get(name);
  if (!path) {
    path = new Path2D(PATHS[name]);
    cache.set(name, path);
  }
  g.save();
  g.translate(cx - size / 2, cy - size / 2);
  g.scale(size / 256, size / 256);
  g.fillStyle = color;
  g.fill(path);
  g.restore();
}

/** Icon + text as one centred line (text baseline middle at y). */
export function drawIconText(
  g: CanvasRenderingContext2D,
  name: CanvasIcon,
  text: string,
  cx: number,
  y: number,
  size: number,
  color: string
) {
  const gap = size * 0.4;
  const w = size + gap + g.measureText(text).width;
  const left = cx - w / 2;
  const prevAlign = g.textAlign;
  const prevBase = g.textBaseline;
  drawIcon(g, name, left + size / 2, y, size, color);
  g.textAlign = "left";
  g.textBaseline = "middle";
  g.fillStyle = color;
  g.fillText(text, left + size + gap, y);
  g.textAlign = prevAlign;
  g.textBaseline = prevBase;
}
